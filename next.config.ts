import type { NextConfig } from "next";

// Headers that do not vary per request. The Content Security Policy needs a per-request nonce
// and is set in src/proxy.ts instead.
const securityHeaders = [
  // Only ever load this site over HTTPS once it has been seen on HTTPS (ignored on plain http).
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=(), usb=()" },
  // Opt out of browser features that could leak cross-origin data.
  { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [{ source: "/(.*)", headers: securityHeaders }];
  },
};

export default nextConfig;
